// Make the lower-resolution copies of existing PNGs that the game ships for some tiers.
// No new art: every output is a box-filtered copy of a file already in public/.
//
//   node tools/assets/derive_lowres.mjs          write the files and tools/assets/derived.json
//   node tools/assets/derive_lowres.mjs --check  fail if a file or the record is out of date
//
// Needs Node only (zlib). The record lists, per output, the source it came from (by hash), the factor,
// the file size and two hashes: of the file bytes (zlib output can differ between Node versions) and of
// the decoded pixels (which cannot). tests/derived-assets.test.js compares pixels.

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { decodePng, encodePng, boxDownsample } from './png.mjs';

const root = new URL('../../public/', import.meta.url);
const record = new URL('./derived.json', import.meta.url);
const meansModule = new URL('../../src/modes/town/render/paintedMeans.js', import.meta.url);

/** What is derived from what, and why. `srgb` keeps the sRGB chunk the source carries. */
export const DERIVED = [
  { output: 'textures/skirmish_surfaces_256.png', source: 'textures/skirmish_surfaces.png', factor: 2, srgb: false,
    why: 'the town shrinks every painted layer from 512 to 256 at run time; this is that result, computed once' },
  { output: 'textures/soldier_v5_m_cloth_1024.png', source: 'textures/soldier_v5_m_cloth.png', factor: 2, srgb: true, why: 'Low tier: 1024 character atlas' },
  { output: 'textures/soldier_v5_f_cloth_1024.png', source: 'textures/soldier_v5_f_cloth.png', factor: 2, srgb: true, why: 'Low tier: 1024 character atlas' },
  { output: 'textures/soldier_v5_m_head_1024.png', source: 'textures/soldier_v5_m_head.png', factor: 2, srgb: true, why: 'Low tier: 1024 face atlas' },
  { output: 'textures/soldier_v5_f_head_1024.png', source: 'textures/soldier_v5_f_head.png', factor: 2, srgb: true, why: 'Low tier: 1024 face atlas' }
];

const sha = (buffer) => createHash('sha256').update(buffer).digest('hex');

/**
 * The mean colour (linear) of each tile of the 512 surface file, by the same sampling as the loader
 * (skirmish/battlefield/envKit.js loadSurfaces: every 7th pixel). The ground divides by it. The 256 file
 * would give slightly different numbers (up to 1.3 % off on one channel), so the town is handed the
 * numbers of the original and its look does not move.
 */
export function surfaceMeans(image) {
  const size = image.width, layers = image.height / size, out = [];
  const lin = (c) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);
  for (let layer = 0; layer < layers; layer++) {
    const sum = [0, 0, 0], base = layer * size * size, n = Math.ceil((size * size) / 7);
    for (let i = 0; i < size * size; i += 7) for (let c = 0; c < 3; c++) sum[c] += lin(image.data[(base + i) * image.channels + c] / 255);
    out.push(sum.map((v) => v / n));
  }
  return out;
}

export const meansSource = (means) => `// Generated by tools/assets/derive_lowres.mjs from textures/skirmish_surfaces.png. Do not edit.
// Mean colour (linear RGB) of each of the 22 painted tiles of the 512 file: the town divides by it to keep
// only a tile's pattern, and the 256-pixel copy it loads would give slightly different numbers.
export const PAINTED_SURFACE_MEANS = ${JSON.stringify(means)};
`;
const surfaceMeansSource = () => meansSource(surfaceMeans(decodePng(readFileSync(new URL('textures/skirmish_surfaces.png', root)))));

/** The derived image for one entry: { image, bytes (PNG file), source: Buffer }. */
export function derive(entry) {
  const source = readFileSync(new URL(entry.source, root));
  const image = boxDownsample(decodePng(source), entry.factor);
  return { image, bytes: encodePng(image, { srgb: entry.srgb }), source };
}

export function describe(entry) {
  const { image, bytes, source } = derive(entry);
  return { output: entry.output, source: entry.source, factor: entry.factor, why: entry.why, width: image.width, height: image.height,
    sourceSha256: sha(source), bytes: bytes.length, fileSha256: sha(bytes), pixelsSha256: sha(image.data) };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  const entries = DERIVED.map((entry) => ({ entry, info: describe(entry) }));
  const next = JSON.stringify({ generator: 'tools/assets/derive_lowres.mjs', method: 'box filter, rounded mean of each factor x factor block, per channel', derived: entries.map((e) => e.info) }, null, 2) + '\n';
  if (check) {
    const old = existsSync(record) ? JSON.parse(readFileSync(record, 'utf8')) : { derived: [] };
    let stale = 0;
    for (const { info } of entries) {
      const was = old.derived.find((d) => d.output === info.output);
      const onDisk = existsSync(new URL(info.output, root)) ? decodePng(readFileSync(new URL(info.output, root))) : null;
      const pixelsOk = onDisk && sha(onDisk.data) === info.pixelsSha256;
      if (!was || was.sourceSha256 !== info.sourceSha256 || was.pixelsSha256 !== info.pixelsSha256 || !pixelsOk) { stale++; console.error(`out of date: ${info.output}`); }
    }
    if (!existsSync(meansModule) || readFileSync(meansModule, 'utf8') !== surfaceMeansSource()) { stale++; console.error('out of date: src/modes/town/render/paintedMeans.js'); }
    if (stale) process.exit(1);
    console.log(`derived assets up to date (${entries.length})`);
  } else {
    for (const { entry } of entries) {
      const { bytes } = derive(entry);
      writeFileSync(new URL(entry.output, root), bytes);
      console.log(`${entry.output}  ${bytes.length} bytes`);
    }
    writeFileSync(meansModule, surfaceMeansSource());
    writeFileSync(record, next);
    console.log('wrote tools/assets/derived.json and src/modes/town/render/paintedMeans.js');
  }
}
